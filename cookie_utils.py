"""
Cookie 导出工具（简化版）
使用 Playwright 从浏览器获取 Cookie（无需解密）
"""
import os
import json
from pathlib import Path

def export_cookies_with_playwright(output_path):
    """
    使用 Playwright 启动 Chrome，获取 Bilibili Cookie
    需要安装：pip install playwright
    """
    try:
        from playwright.sync_api import sync_playwright
        
        with sync_playwright() as p:
            # 使用现有的 Chrome 用户数据（这样会自动加载登录状态）
            user_data_dir = str(Path.home() / "AppData" / "Local" / "Google" / "Chrome" / "User Data")
            
            browser = p.chromium.launch_persistent_context(
                user_data_dir=user_data_dir,
                headless=True,
                channel="chrome"
            )
            
            page = browser.pages[0] if browser.pages else browser.new_page()
            page.goto("https://www.bilibili.com", wait_until="networkidle")
            
            # 获取 Cookie
            cookies = page.context.cookies()
            browser.close()
            
            # 保存为 Netscape 格式
            with open(output_path, 'w', encoding='utf-8') as f:
                f.write("# Netscape HTTP Cookie File\n")
                f.write("# This file was generated by B站视频下载助手\n")
                f.write("\n")
                
                for cookie in cookies:
                    domain = cookie['domain']
                    flag = 'TRUE' if domain.startswith('.') else 'FALSE'
                    path = cookie['path']
                    secure = 'TRUE' if cookie.get('secure') else 'FALSE'
                    expiration = cookie.get('expires', 0)
                    name = cookie['name']
                    value = cookie['value']
                    
                    f.write(f"{domain}\t{flag}\t{path}\t{secure}\t{expiration}\t{name}\t{value}\n")
            
            return True, f"✅ Cookie 已保存到：{output_path}"
            
    except ImportError:
        return False, "❌ 未安装 Playwright，请运行：pip install playwright"
    except Exception as e:
        return False, f"❌ 导出失败：{str(e)}"

def auto_export_bilibili_cookies(output_path=None):
    """
    自动从 Chrome 提取 Bilibili Cookie 并导出
    返回 (success, message)
    """
    if output_path is None:
        output_path = Path.home() / "Downloads" / "bilibili_cookies.txt"
    
    # 使用 Playwright 方法（最可靠）
    return export_cookies_with_playwright(output_path)

